-- Cada usuário autenticado só acessa os próprios registros.
create table if not exists public.production_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_date date not null,
  product_stage text not null,
  quantity numeric(14,2) not null default 0 check (quantity >= 0),
  goal numeric(14,2) not null default 0 check (goal >= 0),
  notes text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.inventory_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null default 'Outro',
  quantity numeric(14,2) not null default 0 check (quantity >= 0),
  minimum numeric(14,2) not null default 0 check (minimum >= 0),
  unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
  unit text not null default 'kg',
  created_at timestamptz not null default now()
);
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('sale','expense')),
  record_date date not null,
  description text not null,
  amount numeric(14,2) not null check (amount > 0),
  created_at timestamptz not null default now()
);
alter table public.production_records enable row level security;
alter table public.inventory_items enable row level security;
alter table public.transactions enable row level security;
create policy "Users manage own production" on public.production_records for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own inventory" on public.inventory_items for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own transactions" on public.transactions for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
